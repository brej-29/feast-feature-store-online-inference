#!/usr/bin/env python
"""Export MLflow runs to models/EXPERIMENTS.md.

The MLflow tracking store (mlruns/) is gitignored -- it's a local artifact
store, not source. This renders the runs into one committed markdown table so
the experiment history is visible in the repo (and in the README) without
needing a hosted tracking server.

Regenerate:  python scripts/export_experiments.py
Browse live: mlflow ui   (then open http://127.0.0.1:5000)
"""

import os
from typing import List

OUT_PATH = os.path.join("models", "EXPERIMENTS.md")

# Metrics worth putting in the comparison table, in display order.
COLUMNS = [
    ("pr_auc", "PR-AUC", 4),
    ("roc_auc", "ROC-AUC", 4),
    ("recall_at_precision_0.90", "Recall@P90", 4),
    ("brier_score", "Brier", 5),
    ("threshold_max_f1", "Threshold", 4),
]


def main() -> None:
    import mlflow

    runs = mlflow.search_runs(
        experiment_names=["fraud_feature_store"], order_by=["attributes.start_time ASC"]
    )
    if runs.empty:
        print("No MLflow runs found. Run pipelines/train_model.py first.")
        return

    lines: List[str] = [
        "# Experiment log",
        "",
        "Generated by `scripts/export_experiments.py` from the local MLflow "
        "tracking store. Browse interactively with `mlflow ui`.",
        "",
        "| Run | class_weight | rows | features | " + " | ".join(c[1] for c in COLUMNS) + " |",
        "|---|---|---|---|" + "---|" * len(COLUMNS),
    ]

    for _, r in runs.iterrows():
        cw = r.get("params.class_weight", "?")
        rows = r.get("params.max_rows", "?")
        ftd = str(r.get("params.feature_table_dir", "") or "")
        feats = "full (6.3M)" if ftd and "processed" not in ftd.split("/")[-1] else "sample (300k)"
        prod = " ✅" if str(r.get("params.saved_as_production", "")).lower() == "true" else ""
        cells = []
        for key, _, digits in COLUMNS:
            val = r.get(f"metrics.{key}")
            cells.append("—" if val is None else f"{float(val):.{digits}f}")
        started = str(r.get("start_time", ""))[:16]
        lines.append(
            f"| {started}{prod} | `{cw}` | {rows} | {feats} | " + " | ".join(cells) + " |"
        )

    lines += [
        "",
        "✅ = the run whose artifact is committed under `models/` and served by the API.",
        "",
        "## Reading these",
        "",
        "**`class_weight`** is the D010 finding, re-runnable rather than quoted from "
        "memory: `python -m pipelines.train_model --class_weight none --no_save`. "
        "Unweighted at ~0.3% prevalence, the model saturates and no threshold reaches "
        "90% precision at all.",
        "",
        "**`features: full (6.3M)`** uses entity profiles built by the Spark pipeline "
        "over the whole dataset instead of a 300k subsample "
        "(`scripts/train_on_full_dataset.sh`), holding training rows constant so the "
        "variable under test is feature richness rather than training-set size.",
        "",
        "Caveat worth stating plainly: the sample and full runs draw different row "
        "samples, so their test windows are not identical and the headline metrics are "
        "not a strict A/B. Read the full-dataset row as 'no ranking improvement, "
        "materially better calibration' -- Brier drops and the operating threshold "
        "lands near 0.5 instead of 0.97 -- not as a like-for-like win or loss.",
        "",
    ]

    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Wrote {OUT_PATH} ({len(runs)} runs)")


if __name__ == "__main__":
    main()
